-- ============================================================================
-- 034_support_tickets.sql
-- Support tickets: a client raises an issue from Support in the app, with
-- screenshots and screen recordings; the BigLead owner answers from
-- /owner-admin/tickets. Both sides get an email on each new message.
--
--   support_tickets              One issue. Numbered from 1001 (shown BL-1001).
--   support_ticket_messages      The thread: the first message is the
--                                description; then replies from either side.
--   support_ticket_attachments   Files in the private support-attachments
--                                bucket, each tied to the message it came with.
--
-- All three are service-role only: every read and write goes through server
-- code that checks the company (and the owner session for the owner side).
-- ============================================================================

CREATE TABLE IF NOT EXISTS support_tickets (
  id              UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  ticket_number   BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) UNIQUE,
  company_id      UUID NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  created_by      UUID REFERENCES users(id) ON DELETE SET NULL,
  subject         TEXT NOT NULL CHECK (char_length(subject) BETWEEN 3 AND 200),
  category        TEXT NOT NULL DEFAULT 'OTHER'
                  CHECK (category IN ('LEADS', 'WHATSAPP', 'BILLING', 'TEAM', 'BUG', 'FEATURE', 'OTHER')),
  priority        TEXT NOT NULL DEFAULT 'NORMAL'
                  CHECK (priority IN ('NORMAL', 'HIGH', 'URGENT')),
  status          TEXT NOT NULL DEFAULT 'OPEN'
                  CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
  -- Browser, screen size and the page they came from: helps reproduce a bug.
  context         JSONB NOT NULL DEFAULT '{}',
  last_message_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_message_by TEXT NOT NULL DEFAULT 'CLIENT' CHECK (last_message_by IN ('CLIENT', 'SUPPORT')),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_support_tickets_company ON support_tickets(company_id, last_message_at DESC);
CREATE INDEX IF NOT EXISTS idx_support_tickets_status ON support_tickets(status, last_message_at DESC);

CREATE TABLE IF NOT EXISTS support_ticket_messages (
  id              UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  ticket_id       UUID NOT NULL REFERENCES support_tickets(id) ON DELETE CASCADE,
  author_type     TEXT NOT NULL CHECK (author_type IN ('CLIENT', 'SUPPORT')),
  author_user_id  UUID REFERENCES users(id) ON DELETE SET NULL,
  body            TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 10000),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_support_messages_ticket ON support_ticket_messages(ticket_id, created_at);

CREATE TABLE IF NOT EXISTS support_ticket_attachments (
  id              UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  ticket_id       UUID NOT NULL REFERENCES support_tickets(id) ON DELETE CASCADE,
  message_id      UUID REFERENCES support_ticket_messages(id) ON DELETE CASCADE,
  storage_path    TEXT NOT NULL UNIQUE,
  file_name       TEXT NOT NULL,
  mime_type       TEXT NOT NULL,
  size_bytes      BIGINT NOT NULL CHECK (size_bytes > 0),
  kind            TEXT NOT NULL CHECK (kind IN ('IMAGE', 'VIDEO', 'FILE')),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_support_attachments_ticket ON support_ticket_attachments(ticket_id);

ALTER TABLE support_tickets ENABLE ROW LEVEL SECURITY;             -- service role only
ALTER TABLE support_ticket_messages ENABLE ROW LEVEL SECURITY;     -- service role only
ALTER TABLE support_ticket_attachments ENABLE ROW LEVEL SECURITY;  -- service role only

